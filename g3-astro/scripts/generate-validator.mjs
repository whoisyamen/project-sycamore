import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import addFormats from 'ajv-formats';
import prettier from 'prettier';
import standaloneCode from 'ajv/dist/standalone/index.js';
const schema = async (name) =>
  JSON.parse(
    await readFile(new URL(`../../shared/schemas/${name}.schema.json`, import.meta.url), 'utf8'),
  );
const ajv = new Ajv({ allErrors: true, code: { source: true, esm: true, lines: true } });
addFormats(ajv);
ajv.addSchema(await schema('event'), 'event.schema.json');
ajv.addSchema(await schema('manifest'), 'manifest.schema.json');
const validator = ajv.compile(await schema('snapshot'));
// Precompiled code avoids runtime Function()/unsafe-eval in the public bundle.
const code = standaloneCode(ajv, validator)
  .replaceAll('require("ajv-formats/dist/formats")', 'formats')
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
await writeFile(
  new URL('../src/data/generated-validator.js', import.meta.url),
  '// @ts-nocheck\n// Generated by npm run generate:validator. Do not edit.\nimport lengthModule from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = lengthModule.default ?? lengthModule;\nimport formats from "ajv-formats/dist/formats.js";\n' +
    code +
    '\n',
);

// Iteration 1.1.2: separate intelligence validators (record/index/detail).
// All schemas compile in ONE Ajv instance (registered under ids) and are
// emitted together via array-style standaloneCode, so internal helper names
// (schemaN, patternN) stay unique. Export names come from the keys below.
// The existing snapshot validator is untouched above.
const intNames = ['record', 'index', 'detail'];
const intAjv = new Ajv({ allErrors: true, code: { source: true, esm: true, lines: true } });
addFormats(intAjv);
for (const name of intNames) {
  intAjv.addSchema(await schema(`intelligence/${name}`), `intelligence/${name}`);
}
const intExports = Object.fromEntries(
  intNames.map((name) => [`validate${cap(name)}`, `intelligence/${name}`]),
);
let intCode = standaloneCode(intAjv, intExports)
  .replaceAll('require("ajv-formats/dist/formats")', 'formats')
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length');
const intValidatorUrl = new URL('../src/data/generated-intelligence-validator.js', import.meta.url);
const prettierConfig = await prettier.resolveConfig(fileURLToPath(intValidatorUrl));
intCode = await prettier.format(
  '// @ts-nocheck\n// Generated by npm run generate:validator. Do not edit.\nimport lengthModule from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = lengthModule.default ?? lengthModule;\nimport formats from "ajv-formats/dist/formats.js";\n' +
    intCode,
  { ...prettierConfig, filepath: fileURLToPath(intValidatorUrl) },
);
await writeFile(intValidatorUrl, intCode);
await writeFile(
  new URL('../src/data/generated-intelligence-validator.d.ts', import.meta.url),
  '// Generated by npm run generate:validator. Do not edit.\n' +
    intNames
      .map((n) => `export declare function validate${cap(n)}(value: unknown): boolean;`)
      .join('\n') +
    '\n',
);

function cap(name) {
  return name.charAt(0).toUpperCase() + name.slice(1);
}
